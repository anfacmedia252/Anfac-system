require('dotenv').config({ path: '.env.local', quiet: true });

const { Pool } = require('@neondatabase/serverless');

let pool;
let initialization;

function getPool() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL is required. Connect a Neon database before starting the app.');
  }
  if (!pool) {
    pool = new Pool({ connectionString: process.env.DATABASE_URL });
    pool.on('error', error => console.error('Neon database pool error:', error));
  }
  return pool;
}

async function initializeDatabase() {
  if (!initialization) {
    initialization = (async () => {
      const database = getPool();
      await database.query(`
        CREATE TABLE IF NOT EXISTS transactions (
          id TEXT PRIMARY KEY,
          date TEXT NOT NULL,
          type TEXT NOT NULL,
          title TEXT NOT NULL,
          category TEXT NOT NULL,
          method TEXT NOT NULL,
          amount DOUBLE PRECISION NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS campaigns (
          id TEXT PRIMARY KEY,
          name TEXT NOT NULL,
          client TEXT NOT NULL,
          budget DOUBLE PRECISION NOT NULL,
          spent DOUBLE PRECISION NOT NULL DEFAULT 0,
          status TEXT NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS clients (
          id TEXT PRIMARY KEY,
          name TEXT NOT NULL,
          retainer DOUBLE PRECISION NOT NULL,
          status TEXT NOT NULL,
          campaigns INTEGER NOT NULL DEFAULT 1,
          logo TEXT,
          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS projects (
          id TEXT PRIMARY KEY,
          title TEXT NOT NULL,
          client TEXT NOT NULL,
          category TEXT NOT NULL,
          deadline TEXT NOT NULL,
          status TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS bookings (
          id TEXT PRIMARY KEY,
          title TEXT NOT NULL,
          client TEXT NOT NULL,
          datetime TEXT NOT NULL,
          status TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS equipment (
          id TEXT PRIMARY KEY,
          name TEXT NOT NULL,
          category TEXT NOT NULL,
          serial_no TEXT NOT NULL,
          status TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS staff (
          id TEXT PRIMARY KEY,
          name TEXT NOT NULL,
          department TEXT NOT NULL,
          role TEXT NOT NULL,
          salary DOUBLE PRECISION NOT NULL
        );
        CREATE TABLE IF NOT EXISTS profile (
          id INTEGER PRIMARY KEY CHECK (id = 1),
          first_name TEXT NOT NULL,
          last_name TEXT NOT NULL,
          email TEXT NOT NULL,
          role TEXT NOT NULL,
          photo TEXT
        );
        CREATE TABLE IF NOT EXISTS app_users (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          username TEXT NOT NULL UNIQUE,
          password_hash TEXT NOT NULL,
          role TEXT NOT NULL CHECK (role IN ('admin', 'staff')),
          staff_id TEXT UNIQUE,
          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS app_sessions (
          token_hash TEXT PRIMARY KEY,
          user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
          expires_at TIMESTAMPTZ NOT NULL
        );
        CREATE INDEX IF NOT EXISTS app_sessions_expiry_idx ON app_sessions (expires_at);
        CREATE TABLE IF NOT EXISTS app_state (
          id INTEGER PRIMARY KEY CHECK (id = 1),
          state_json JSONB NOT NULL,
          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
      `);
      await database.query(`
        INSERT INTO profile (id, first_name, last_name, email, role, photo)
        VALUES (1, 'Administrator', '', 'anfacmedia252@gmail.com', 'Administrator', '')
        ON CONFLICT (id) DO NOTHING
      `);
    })().catch(error => {
      initialization = undefined;
      throw error;
    });
  }
  return initialization;
}

module.exports = { getPool, initializeDatabase };
